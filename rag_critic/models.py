"""
rag_critic.models
~~~~~~~~~~~~~~~~~
Pydantic data models and schemas for atomic claims, validation status, and critic results.
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ClaimStatus(str, Enum):
    """The factual grounding status of an individual atomic claim."""
    SUPPORTED = "SUPPORTED"
    CONTRADICTED = "CONTRADICTED"
    UNGROUNDED = "UNGROUNDED"


class Claim(BaseModel):
    """An indivisible, atomic factual proposition extracted from an LLM draft response."""
    id: int = Field(description="Sequential identifier of the claim")
    text: str = Field(description="The atomic proposition text")
    status: ClaimStatus = Field(
        default=ClaimStatus.UNGROUNDED,
        description="Verification outcome against the provided context"
    )
    citation_chunk_index: Optional[int] = Field(
        default=None,
        description="Index of the retrieved context chunk that proves or refutes the claim"
    )
    confidence: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Confidence score of the verification decision"
    )
    explanation: str = Field(
        default="",
        description="Brief diagnostic justification for the claim status"
    )


class ChunkContext(BaseModel):
    """A retrieved source document chunk used as ground-truth context."""
    index: int
    text: str
    metadata: Dict[str, Any] = Field(default_factory=dict)


class CriticResult(BaseModel):
    """The comprehensive evaluation report generated by RAGCritic."""
    grounding_score: float = Field(
        ge=0.0,
        le=1.0,
        description="Ratio of SUPPORTED claims to total claims (1.0 = perfectly grounded)"
    )
    hallucination_index: float = Field(
        ge=0.0,
        le=1.0,
        description="Normalized severity of ungrounded and contradicted claims"
    )
    is_grounded: bool = Field(
        description="Whether the grounding_score meets or exceeds the required threshold"
    )
    status: str = Field(
        description="High-level decision: 'APPROVED' or 'REJECTED_HALLUCINATION'"
    )
    total_claims: int
    supported_claims: int
    ungrounded_claims: int
    contradicted_claims: int
    claims: List[Claim] = Field(default_factory=list)
    citations: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Verifiable source citations mapped directly to source chunks"
    )
    revision_feedback: Optional[str] = Field(
        default=None,
        description="Actionable diagnostic instructions for re-writer agents when hallucinations are caught"
    )
    clean_response: Optional[str] = Field(
        default=None,
        description="Draft answer with ungrounded/contradicted statements automatically redacted"
    )

    def summary(self) -> str:
        """Return a human-readable diagnostic summary."""
        state = "APPROVED" if self.is_grounded else "FLAGGED"
        return (
            f"[RAG-CRITIC: {state}] Grounding Score: {self.grounding_score:.1%} | "
            f"Supported: {self.supported_claims}/{self.total_claims} | "
            f"Ungrounded: {self.ungrounded_claims} | Contradicted: {self.contradicted_claims}"
        )
